-- Transactional outbox: written in the same transaction as the aggregate change.
-- The identity column gives a total order for the relay; event_id is the public, idempotent id.
CREATE TABLE outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        UUID          NOT NULL UNIQUE,
    aggregate_type  VARCHAR(64)   NOT NULL,
    aggregate_id    UUID          NOT NULL,
    event_type      VARCHAR(64)   NOT NULL,
    payload         VARCHAR(8000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_unpublished ON outbox_events (published_at, id);

-- Consumer-side deduplication ("inbox")
CREATE TABLE processed_events (
    event_id      UUID        NOT NULL,
    consumer      VARCHAR(64) NOT NULL,
    processed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_processed_events PRIMARY KEY (event_id, consumer)
);
